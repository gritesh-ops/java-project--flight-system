public class Topic02DataTypes {
    public static void main(String[] args) {
        int seats = 180;
        double fare = 4250.50;
        char terminal = 'A';
        boolean cancelled = false;
        String destination = "Delhi"; // String is a reference type.
        System.out.println(destination + " | " + seats + " | " + fare
                + " | " + terminal + " | Cancelled: " + cancelled);
    }
}

